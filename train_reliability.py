"""Train a frozen-Point query-failure head on Fashion-IQ-C labels.

The Point backbone is intentionally frozen in the reliability probe. This preserves
the validated retrieval function and makes the failure label (generated by that
same checkpoint) stationary.  Retrieval loss is monitored in the documented
total objective; only the failure term updates the new head.
"""

